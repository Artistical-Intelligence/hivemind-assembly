"""Render the current-evidence sections of README and ROADMAP from release_status.json.

`release_status.json` is the single source for version, live-acceptance counts and
current evidence. Each evidence entry names the exact commit and runs it describes,
so a claim cannot silently drift onto a later revision. Run with `--write` after
editing the status file; `tests/test_status_docs.py` fails while the documents and
the status file disagree.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATUS = ROOT / "_app" / "release_status.json"
TARGETS = (ROOT / "README.md", ROOT / "dev" / "ROADMAP.md")
BEGIN, END = "<!-- status:begin -->", "<!-- status:end -->"
RUN = "https://github.com/Artistical-Intelligence/hivemind-assembly/actions/runs/"
FIELDS = {"id", "date", "commit", "runs", "host", "live_model_inference", "summary"}


def validate(status):
    evidence = status.get("evidence")
    if not isinstance(evidence, list) or not evidence:
        raise ValueError("release_status.json needs a non-empty evidence list")
    seen = set()
    for item in evidence:
        if set(item) != FIELDS:
            raise ValueError("Evidence entries need exactly: " + ", ".join(sorted(FIELDS)))
        if item["id"] in seen:
            raise ValueError("Duplicate evidence id: " + item["id"])
        seen.add(item["id"])
        if not re.fullmatch(r"[0-9a-f]{40}", item["commit"]):
            raise ValueError("Evidence must name a full commit SHA: " + item["id"])
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", item["date"]):
            raise ValueError("Evidence date must be YYYY-MM-DD: " + item["id"])
        if not all(type(r) is int and r > 0 for r in item["runs"]):
            raise ValueError("Workflow runs are positive integers: " + item["id"])
        if type(item["live_model_inference"]) is not bool:
            raise ValueError("live_model_inference must be boolean: " + item["id"])
    removed = status.get("run_logs_removed_before")
    if removed is not None:
        if set(removed) != {"run", "date", "reason"} or type(removed["run"]) is not int or removed["run"] <= 0:
            raise ValueError("run_logs_removed_before needs a positive run, a date and a reason")
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", removed["date"]):
            raise ValueError("run_logs_removed_before date must be YYYY-MM-DD")
    live = status["native_live_acceptance"]
    if not 0 <= live["validated_routes"] <= live["required_routes"]:
        raise ValueError("Validated routes outside the required range")
    return evidence


def render(status):
    evidence = validate(status)
    live = status["native_live_acceptance"]
    lines = [
        BEGIN,
        "<!-- Generated by dev/status_docs.py from _app/release_status.json; edit that file. -->",
        "",
        f"**Version {status['version']}.** "
        f"Live native routes accepted: {live['validated_routes']} of {live['required_routes']}. "
        f"Unattended worker/adviser/Ghidra loop with live models: "
        f"{'established' if live['unattended_worker_adviser_ghidra_loop'] else 'not established'}. "
        f"Clean Windows desktop installation: "
        f"{'verified' if live['windows_clean_install'] else 'not verified'}.",
        "",
        "| Evidence | Commit | Runs | Host | Model inference |",
        "| --- | --- | --- | --- | --- |",
    ]
    removed = status.get("run_logs_removed_before")

    def run_cell(run):
        # Runs from before the repository was recreated no longer exist on GitHub; no dead links.
        if removed and run < removed["run"]:
            return f"{run} (log removed)"
        return f"[{run}]({RUN}{run})"

    for item in evidence:
        runs = ", ".join(run_cell(r) for r in item["runs"]) or "local"
        lines.append(
            f"| {item['id']} ({item['date']}) | `{item['commit'][:7]}` | {runs} | "
            f"{item['host']} | {'yes' if item['live_model_inference'] else 'no'} |"
        )
    if removed:
        lines += ["", f"Runs marked “log removed” ran before {removed['date']}. {removed['reason']}"]
    lines.append("")
    for item in evidence:
        lines.append(f"- **{item['id']}** (`{item['commit'][:7]}`): {item['summary']}")
    lines += ["", "Still required:", ""]
    lines += [f"- {entry}" for entry in status["remaining_acceptance"]]
    lines.append(END)
    return "\n".join(lines)


def apply(text, block):
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise ValueError("Document needs exactly one status block")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return text[:start] + block + text[end:]


def check(write=False):
    status = json.loads(STATUS.read_text(encoding="utf-8"))
    block = render(status)
    stale = []
    for path in TARGETS:
        text = path.read_text(encoding="utf-8")
        updated = apply(text, block)
        if updated != text:
            if write:
                path.write_text(updated, encoding="utf-8")
            else:
                stale.append(path.name)
    return stale


if __name__ == "__main__":
    stale = check("--write" in sys.argv)
    if stale:
        print("Out of date: " + ", ".join(stale) + " (run python dev/status_docs.py --write)")
        raise SystemExit(1)
    print("Status documents match release_status.json")
