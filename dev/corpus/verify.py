"""Verify all 96 compiler variants against independently executed native code.

Only source generated by generate.py is executed on the host. This command never
runs an imported target binary. Outputs are engineering evidence, not native-model
learning results or proof of whole-application reconstruction.
"""

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "_app"))
from generate import FAMILIES, generate
from hivemind_assembly.domains.reverse_engineering.reconstruction import (
    extract_function,
    execute_function,
    vectors,
)


def verify(root):
    root = Path(root)
    generated = generate(root)
    if generated["compiled"] != 96:
        raise RuntimeError("Both GCC and Clang are required for the 96-variant corpus")
    manifest = json.loads((root / "manifest.json").read_text())
    outcomes = []
    start = time.perf_counter()
    driver = root / "native_driver.c"
    driver.write_text(
        '#include <stdio.h>\nunsigned target(unsigned,unsigned);int main(void){unsigned a,b;while(scanf("%u %u",&a,&b)==2)printf("%u\\n",target(a,b));return 0;}\n'
    )
    for item in manifest["cases"]:
        name = item["id"].rsplit("_", 2)[0]
        variant = int(name.rsplit("_", 1)[1])
        trusted_source = (
            "__attribute__((noinline)) unsigned target(unsigned a,unsigned b){"
            + FAMILIES[item["family"]][variant]
            + "}\n"
        )
        source = root / (name + ".c")
        if (
            source.read_text() != trusted_source
            or hashlib.sha256(source.read_bytes()).hexdigest() != item["source_sha256"]
        ):
            raise RuntimeError("Generated source was modified; refusing host execution")
        compiler = shutil.which(item["compiler"])
        executable = root / (item["id"] + ".native")
        subprocess.run(
            [
                compiler,
                "-" + item["optimization"],
                str(source),
                str(driver),
                "-o",
                str(executable),
            ],
            check=True,
            capture_output=True,
        )
        cases = vectors([32, 32], item["id"], 32)
        live = subprocess.run(
            [str(executable)],
            input="".join(f"{a} {b}\n" for a, b in cases),
            text=True,
            capture_output=True,
            timeout=10,
            check=True,
        )
        expected = [int(x) for x in live.stdout.splitlines()]
        if len(expected) != len(cases):
            raise RuntimeError("Native reference returned an incomplete vector set")
        obj = root / item["object"]
        if hashlib.sha256(obj.read_bytes()).hexdigest() != item["sha256"]:
            raise RuntimeError("Corpus object changed")
        machine = extract_function(obj.read_bytes(), "target")
        failures = []
        for args, value in zip(cases, expected):
            result = execute_function(machine, args, 32)
            if (
                result["status"] != "completed"
                or not result["abi_ok"]
                or result["value"] != value
            ):
                failures.append(
                    {"arguments": args, "expected": value, "actual": result}
                )
        # Verify a deliberately wrong reconstruction is distinguishable. A
        # constant-zero mutant must fail at least one of these independent cases.
        mutation_rejected = any(value != 0 for value in expected)
        outcomes.append(
            {
                "id": item["id"],
                "family": item["family"],
                "split": item["split"],
                "vectors": len(cases),
                "passed": not failures and mutation_rejected,
                "failures": failures,
                "constant_zero_rejected": mutation_rejected,
            }
        )
    report = {
        "kind": "source_known_native_oracle",
        "variants": len(outcomes),
        "functions": 24,
        "families": 12,
        "compilers": ["gcc", "clang"],
        "optimizations": ["O0", "O2"],
        "passed": sum(x["passed"] for x in outcomes),
        "failed": sum(not x["passed"] for x in outcomes),
        "vector_executions": sum(x["vectors"] for x in outcomes),
        "elapsed": time.perf_counter() - start,
        "cases": outcomes,
    }
    (root / "verification.json").write_text(json.dumps(report, indent=2))
    return {k: v for k, v in report.items() if k != "cases"}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("output")
    result = verify(parser.parse_args().output)
    print(json.dumps(result, indent=2))
    sys.exit(bool(result["failed"]))
