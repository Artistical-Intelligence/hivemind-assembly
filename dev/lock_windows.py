"""Validate downloaded wheels with Windows markers and pin their exact hashes.

pip cross-download uses the host's environment for some dependency markers.
Resolve the metadata closure explicitly for the bundled Windows CPython 3.12.
Missing wheels are errors; this command does not substitute package versions.
"""

import argparse
import email
import hashlib
import json
from pathlib import Path
import zipfile
from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
from packaging.version import Version

ROOT = Path(__file__).resolve().parents[1]


def lock(folder, output):
    records = {}
    for path in Path(folder).glob("*.whl"):
        with zipfile.ZipFile(path) as archive:
            name = next(
                n for n in archive.namelist() if n.endswith(".dist-info/METADATA")
            )
            metadata = email.message_from_bytes(archive.read(name))
        key = canonicalize_name(metadata["Name"])
        if key in records:
            raise ValueError("Ambiguous downloaded wheels: " + key)
        records[key] = (
            Version(metadata["Version"]),
            metadata.get_all("Requires-Dist") or [],
            path,
        )
    env = {
        **default_environment(),
        "sys_platform": "win32",
        "os_name": "nt",
        "platform_system": "Windows",
        "platform_machine": "AMD64",
        "python_version": "3.12",
        "python_full_version": "3.12.10",
        "implementation_name": "cpython",
        "platform_python_implementation": "CPython",
        "extra": "",
    }
    queue = [
        Requirement(line)
        for line in (ROOT / "_app/requirements.txt").read_text().splitlines()
        if line.strip() and not line.startswith("#")
    ]
    visited, active = set(), set()
    while queue:
        req = queue.pop()
        key = canonicalize_name(req.name)
        if key not in records or records[key][0] not in req.specifier:
            raise ValueError("Missing or incompatible Windows wheel: " + str(req))
        identity = (key, tuple(sorted(req.extras)))
        if identity in visited:
            continue
        visited.add(identity)
        active.add(key)
        for raw in records[key][1]:
            dep = Requirement(raw)
            if dep.marker is None or any(
                dep.marker.evaluate({**env, "extra": extra})
                for extra in {"", *req.extras}
            ):
                queue.append(dep)
    lines = [
        "# Windows x86-64 / bundled CPython 3.12.10. Generated by dev/lock_windows.py.",
        "# Complete marker-aware dependency closure; install with --require-hashes --no-deps.",
    ]
    for key in sorted(active):
        version, _, path = records[key]
        sha = hashlib.sha256(path.read_bytes()).hexdigest()
        lines.append(f"{key}=={version} --hash=sha256:{sha}")
    Path(output).write_text("\n".join(lines) + "\n")
    return {
        "packages": len(active),
        "target": "Windows AMD64 CPython 3.12.10",
        "missing": 0,
        "lock": str(output),
    }


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("wheels")
    p.add_argument("--output", default=str(ROOT / "_app/requirements-windows.lock"))
    args = p.parse_args()
    print(json.dumps(lock(args.wheels, args.output), indent=2))
